'use strict';
const assert = require('node:assert/strict');
const ink = require('../../shared/auditInk');
const { createSigningAssets } = require('../../shared/auditSigningAssets');
const { createCanvas } = require('@napi-rs/canvas');
async function main() {
  const history = ink.createHistory(), materials = [];
  const stroke = { type: 'draw', page: 1, width: 0.1, color: '#000000', points: [{ x: 0.2, y: 0.5 }, { x: 0.8, y: 0.5 }] };
  ink.appendOperation(history, { ...stroke, layerId: 'entry-1' });
  ink.appendOperation(history, { ...stroke, layerId: 'entry-1', color: '#ff0000' });
  assert.equal(ink.signingLayers(history, materials, 1).length, 1);
  ink.addMaterial(history, materials, { _idx: 'stamp', page: 1, positionX: 0.5, size: 1, rotation: 0 });
  ink.updateMaterial(history, materials, 'stamp', { positionX: 0.8, size: 2, rotation: 30 });
  assert.equal(materials[0].positionX, 0.8);
  ink.undo(history, materials); assert.equal(materials[0].positionX, 0.5);
  ink.redo(history, materials); assert.equal(materials[0].size, 2);
  ink.appendOperation(history, { ...stroke, layerId: 'entry-2', page: 2 });
  assert.equal(ink.undo(history, materials), 2); assert.equal(ink.redo(history, materials), 2);
  ink.appendOperation(history, { ...stroke, layerId: 'entry-2' });
  const order = () => ink.signingLayers(history, materials, 1).map(item => item.id);
  assert.deepEqual(order(), ['entry-1', 'stamp', 'entry-2']);
  ink.moveLayer(history, materials, 1, 'entry-1', 1);
  assert.deepEqual(order(), ['stamp', 'entry-1', 'entry-2']);
  ink.undo(history, materials); assert.deepEqual(order(), ['entry-1', 'stamp', 'entry-2']);
  ink.redo(history, materials); assert.deepEqual(order(), ['stamp', 'entry-1', 'entry-2']);
  const pageTwoOrder=ink.signingLayers(history,materials,2)[0].order;
  ink.moveLayer(history,materials,1,'entry-2',-1);
  assert.equal(ink.signingLayers(history,materials,2)[0].order,pageTwoOrder,'当前页排序不能修改其他页');
  ink.undo(history,materials);
  ink.deleteLayer(history, materials, 1, 'entry-1'); assert.deepEqual(order(), ['stamp', 'entry-2']);
  ink.undo(history, materials); assert.deepEqual(order(), ['stamp', 'entry-1', 'entry-2']);
  ink.deleteLayer(history, materials, 1, 'stamp'); assert.equal(materials.length, 0);
  ink.undo(history, materials); assert.equal(materials[0].rotation, 30);
  const layer = ink.signingLayers(history, materials, 1).find(item => item.id === 'entry-1');
  const canvas = createCanvas(100, 100); ink.renderStrokeLayer(canvas.getContext('2d'), history, layer, 100, 100);
  assert.deepEqual([...canvas.getContext('2d').getImageData(50,50,1,1).data], [255,0,0,255]);
  ink.appendOperation(history, { ...stroke, layerId: 'entry-3' });
  assert.equal(ink.redo(history, materials), null, '新操作删除旧重做分支');
  while (history.cursor) ink.undo(history, materials);
  assert.equal(materials.length, 0); assert.equal(ink.signingLayers(history, materials, 1).length, 0);
  while (history.cursor < history.operations.length) ink.redo(history, materials);
  assert.equal(materials[0].rotation, 30);
  const continued = ink.createHistory();
  ink.appendOperation(continued, { ...stroke, layerId: 'same-entry' });
  ink.deleteLayer(continued, [], 1, 'same-entry');
  ink.appendOperation(continued, { ...stroke, layerId: 'same-entry', color: '#ff0000' });
  while (continued.cursor) ink.undo(continued, []);
  while (continued.cursor < continued.operations.length) ink.redo(continued, []);
  assert.equal(ink.signingLayers(continued, [], 1)[0].strokes.length, 1, '删除后续写再重做不能隐藏新笔画');
  assert.equal(ink.signingLayers(continued, [], 1)[0].strokes[0].color, '#ff0000');
  let calls = 0, decodes = 0, active = 0, peak = 0;
  const assets = createSigningAssets(async name => { calls++; active++; peak = Math.max(peak, active); await new Promise(resolve => setImmediate(resolve)); active--; return name === 'listMyStamps' ? { status: 'success', stamps: [{ id:'s' }] } : { status: 'success', previewMime:'image/png', data:'encoded', imageData:'data:image/png;base64,encoded' }; }, async src => { decodes++; return { width:100,height:100,src }; });
  const draft = { files: {}, locked:false }, file = { id:'f',fileHash:'hash' };
  const [a,b] = await Promise.all([assets.preview(draft,file,1,true),assets.preview(draft,file,1)]);
  assert.strictEqual(a,b); assert.equal(calls,1); assert.equal(decodes,1);
  await assets.preview(draft,file,1); assert.equal(calls,1,'反复进入保留预览与解码');
  assert.strictEqual(await assets.image(draft,a.src),a.image); assert.equal(decodes,1);
  await Promise.all(Array.from({length:8},(_,i)=>assets.stamp(draft,'s'+i,true))); assert.equal(peak,2);
  await assets.stamp(draft,'s0'); assert.equal(calls,9);
  await assets.preview(draft,{...file,fileHash:'new'},1); assert.equal(calls,10);
  assets.reset(); await assets.preview(draft,file,1); assert.equal(calls,11);
  draft.locked=true; await assert.rejects(assets.preview(draft,file,1));
  let release;
  const late = createSigningAssets(() => new Promise(resolve => { release=resolve; }), async()=>({width:1,height:1}));
  const pending=late.preview({files:{}},file,1); await Promise.resolve(); late.reset(); release({status:'success',data:'a',previewMime:'image/png'}); await assert.rejects(pending);
  let failures=0;
  const retry=createSigningAssets(async()=>{if(!failures++)throw Error('network');return {status:'success',data:'a',previewMime:'image/png'};},async()=>({width:1,height:1}));
  const retryDraft={files:{}};await assert.rejects(retry.preview(retryDraft,file,1));await retry.preview(retryDraft,file,1);assert.equal(failures,2);
  let budgetCalls=0, budgetDecodes=0;
  const bounded=createSigningAssets(async()=>{budgetCalls++;return {status:'success',data:'a',previewMime:'image/png'};},async()=>{budgetDecodes++;return {width:4096,height:4096};});
  const budgetDraft={files:{}};
  await bounded.preview(budgetDraft,file,1);await bounded.preview(budgetDraft,file,2);
  await bounded.preview(budgetDraft,file,1);
  assert.equal(budgetCalls,2,'像素超预算后保留源数据，不重新联网');assert.equal(budgetDecodes,3);
  bounded.pause();
  const queued=bounded.preview(budgetDraft,file,3,true);
  await new Promise(resolve=>setImmediate(resolve));assert.equal(budgetCalls,2,'后台不启动新预取');
  bounded.resume();await queued;assert.equal(budgetCalls,3);
  console.log('步骤图层、全操作撤销重做、逐笔颜色与步骤资源并发/解码/失效检查通过');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
