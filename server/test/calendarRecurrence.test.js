'use strict';
const assert = require('node:assert/strict');
const {normalizeTimes, expand} = require('../src/core/services/calendarRecurrence');
const base = {startDate:'2026-01-01',endDate:'2026-01-01',startTime:'09:00',endTime:'10:00'};
const occurrences = (input,from='2026-01-01T00:00:00Z',to='2026-12-31T23:59:59Z') => expand(normalizeTimes({...base,...input},480),from,to);
assert.equal(occurrences({})[0].startAt,'2026-01-01T01:00:00.000Z');
assert.equal(occurrences({recurrence:{frequency:'daily',interval:2,count:3}}).length,3);
assert.deepEqual(occurrences({recurrence:{frequency:'weekly',weekdays:[1,3,5],count:4}}).map(x=>x.occurrenceDate),['2026-01-02','2026-01-05','2026-01-07','2026-01-09']);
assert.deepEqual(occurrences({startDate:'2026-01-31',endDate:'2026-01-31',recurrence:{frequency:'monthly',count:3}}).map(x=>x.occurrenceDate),['2026-01-31','2026-03-31','2026-05-31']);
assert.deepEqual(occurrences({startDate:'2024-02-29',endDate:'2024-02-29',recurrence:{frequency:'yearly'}},'2028-01-01T00:00:00Z','2028-12-31T00:00:00Z').map(x=>x.occurrenceDate),['2028-02-29']);
assert.equal(occurrences({allDay:true,endDate:'2026-01-03'})[0].endAt,'2026-01-02T16:00:00.000Z');
assert.equal(occurrences({startDate:'2025-12-31',endDate:'2026-01-02'}).length,1);
assert.equal(occurrences({recurrence:{frequency:'daily',until:'2026-01-02'}}).length,2);
assert.equal(occurrences({startDate:'2000-01-01',endDate:'2000-01-01',recurrence:{frequency:'daily'}}).length,365);
assert.throws(()=>normalizeTimes({...base,startDate:'2026-02-30'},480));
assert.throws(()=>normalizeTimes({...base,recurrence:{frequency:'daily',count:2,until:'2026-02-01'}},480));
assert.throws(()=>normalizeTimes({...base,recurrence:{frequency:'weekly',weekdays:[0]}},480));
assert.throws(()=>occurrences({},'2026-01-01','2029-01-01'));
console.log('PASS 日程时区、跨天、全天、每日间隔、星期组合、月末、闰年、次数/截止及查询跨度校验');
