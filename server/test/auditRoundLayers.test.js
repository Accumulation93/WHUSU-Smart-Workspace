'use strict';
const assert = require('node:assert/strict');
const { createCanvas } = require('@napi-rs/canvas');
const ink = require('../../shared/auditInk');
const { groupAuditRounds } = require('../../shared/auditStepView');
const { createPreviewPixelsCache } = require('../src/modules/audit/utils/previewPixelsCache');

async function main() {
  const steps = [{ round: 1, status: 'approved' }, { round: 2, status: 'rejected' }, { round: 3, status: 'pending' }];
  const events = [{ round: 1, eventType: 'withdraw' }, { round: 2, eventType: 'reject' }, { round: 3, eventType: 'withdraw' }];
  const rounds = groupAuditRounds({ status: 'withdrawn' }, steps, events);
  assert.deepEqual(rounds.map(item => [item.status, item.expanded]), [['withdrawn', false], ['rejected', false], ['withdrawn', true]]);
  assert.equal(groupAuditRounds({ status: 'rejected' }, [], [{ round: 4, eventType: 'reject' }])[0].expanded, true);
  const history = ink.createHistory();
  const stroke = { type: 'draw', page: 1, width: 0.08, color: '#000000', points: [{ x: 0.1, y: 0.5 }, { x: 0.9, y: 0.5 }] };
  ink.appendOperation(history, stroke);
  const stamp = { _idx: 'stamp', page: 1, layerOrder: ink.nextLayerOrder() };
  ink.appendOperation(history, { ...stroke, color: '#ff0000' });
  let layers = ink.signingLayers(history, [stamp], 1);
  assert.deepEqual(layers.map(layer => layer.kind), ['draw', 'material', 'draw']);
  assert(ink.moveLayer(history, [stamp], 1, stamp._idx, 1));
  assert.deepEqual(ink.signingLayers(history, [stamp], 1).map(layer => layer.kind), ['draw', 'draw', 'material']);
  assert(!ink.moveLayer(history, [stamp], 1, stamp._idx, 1));
  ink.appendOperation(history, { ...stroke, type: 'erase', points: [{ x: 0.5, y: 0.5 }] });
  ink.appendOperation(history, { ...stroke, color: '#0000ff' });
  layers = ink.signingLayers(history, [stamp], 1);
  const canvas = createCanvas(400, 400), ctx = canvas.getContext('2d');
  const old = layers.find(layer => layer.kind === 'draw');
  ink.renderStrokeLayer(ctx, history, old, 400, 400);
  assert.equal(ctx.getImageData(200, 200, 1, 1).data[3], 0);
  ctx.clearRect(0, 0, 400, 400);
  ink.renderStrokeLayer(ctx, history, layers[layers.length - 1], 400, 400);
  assert.deepEqual(Array.from(ctx.getImageData(200, 200, 1, 1).data), [0, 0, 255, 255], '先前橡皮擦不能擦掉后来新增的笔迹');
  const region = ink.strokeExportRegion(stroke, 4096, 4096);
  assert(region.height < 350 && region.width < 3700, '只扫描单笔包围区域');
  const saved = ink.clone(history); ink.undo(history); ink.redo(history); assert.deepEqual(history, saved);
  ink.appendOperation(history, { type: 'clear', page: 1 });
  assert.deepEqual(ink.signingLayers(history, [stamp], 1).map(layer => layer.id), ['stamp']);
  ink.undo(history); assert.equal(ink.signingLayers(history, [stamp], 1).length, 4);
  const many = ink.createHistory();
  for (let i = 0; i < 200; i++) ink.appendOperation(many, { ...stroke, layerId: i < 100 ? 'entry-one' : 'entry-two' });
  assert.equal(ink.inkExportGroups(many, [], 1).length, 2, '两次进入各形成一个图层，不会变成两百份材料');
  const middle = { _idx: 'middle', page: 1, layerOrder: many.operations[99].layerOrder + 0.5 };
  const groups = ink.inkExportGroups(many, [middle], 1);
  assert.equal(groups.length, 2, '合并不得跨越印章');
  const area = ink.groupExportRegion(groups[0], 400, 400), output = createCanvas(area.width, area.height);
  ink.renderExportGroup(output.getContext('2d'), createCanvas(1, 1), many, groups[0], 400, 400, area);
  assert(output.getContext('2d').getImageData(200 - area.left, 200 - area.top, 1, 1).data[3] > 0);
  let calls = 0;
  const cache = createPreviewPixelsCache({ maxEntries: 2, maxBytes: 300, maxAge: 1000 });
  const make = async () => { calls++; return { data: 'pixels' }; };
  const results = await Promise.all([cache.get('org|hash|page|format', make), cache.get('org|hash|page|format', make)]);
  assert.equal(calls, 1); assert.deepEqual(results[0], results[1]);
  await cache.get('org|newhash|page|format', make); await cache.get('otherorg|hash|page|format', make); assert.equal(calls, 3);
  await cache.get('org|hash|page|format', make); assert.equal(calls, 4, '容量有界并淘汰旧项');
  await assert.rejects(cache.get('bad', async () => { throw Error('decode_failed'); }));
  await cache.get('bad', make); assert.equal(calls, 5, '失败不能缓存');
  console.log('轮次状态、最新展开、逐笔图层、擦除范围、导出区域与预览缓存检查通过');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
