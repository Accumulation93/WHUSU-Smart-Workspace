/**
 * Unified score computation engine.
 * Used by BOTH admin getScoreResults AND user getPublicResults.
 *
 * Key guarantees:
 * 1. Scorer's CURRENT identity/department must match a current rate_target_rule.
 *    If identity changed, old records under the old identity are excluded.
 * 2. Template config signature must match current configuration.
 *    Stale template records are excluded.
 * 3. requireAllComplete is respected — if a scorer hasn't finished all
 *    required targets under a clause, their scores are excluded.
 * 4. Scores are grouped by (targetId, scorerCategoryKey, templateId) —
 *    same 3-D grouping used by admin overview.
 * 5. Group-level calc method (weighted_average / trim_extremes) is applied
 *    identically for admin and user views.
 */
const { safeString, toNumber, roundScore } = require('./helpers');
const pool = require('../config/db');

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

// Must match EXACTLY the format generated by buildTemplateConfigSignature in getScoreResults
// (the same function that wrote template_config_signature into score_records)
// Uses question COUNT (not full parameters) so score-range changes don't invalidate records.
function buildTemplateSignature(configs, templatesById) {
  return (configs || [])
    .map(function(config) {
      var template = templatesById.get(safeString(config.template_id));
      if (!template || !Array.isArray(template.questions) || !template.questions.length) return '';
      var qCount = template.questions.length;
      var method = safeString(config.calculation_method || 'weighted_average');
      var trimH = Number(config.trim_high_count || 0);
      var trimL = Number(config.trim_low_count || 0);
      return safeString(config.template_id) + '[' + qCount + '|' + method + '|' + trimH + '|' + trimL + ']';
    })
    .filter(Boolean)
    .join('|');
}

/**
 * Normalize a legacy (full-parameter) signature to the structure-only format.
 * Legacy: templateId[min:start:max:step,...|method|trimH|trimL]
 * Structure: templateId[questionCount|method|trimH|trimL]
 */
function normalizeSignatureToStructure(sig) {
  if (!sig) return null;
  var parts = [];
  var depth = 0, start = 0;
  for (var i = 0; i < sig.length; i++) {
    if (sig[i] === '[') depth++;
    else if (sig[i] === ']') depth--;
    else if (sig[i] === '|' && depth === 0) { parts.push(sig.substring(start, i)); start = i + 1; }
  }
  parts.push(sig.substring(start));

  var normalized = parts.map(function(part) {
    var bracketIdx = part.indexOf('[');
    if (bracketIdx === -1) return part;
    var templateId = part.substring(0, bracketIdx);
    var inner = part.substring(bracketIdx + 1, part.length - 1);
    var innerParts = inner.split('|');
    if (innerParts.length < 4) return part;
    var methodAndTrim = innerParts.slice(-3).join('|');
    var beforeMethod = innerParts.slice(0, -3).join('|');
    var questionCount;
    if (beforeMethod.indexOf(':') !== -1) {
      questionCount = beforeMethod.split(',').filter(function(s) { return s.indexOf(':') !== -1; }).length;
    } else {
      questionCount = parseInt(beforeMethod, 10);
      if (isNaN(questionCount)) return part;
    }
    return templateId + '[' + questionCount + '|' + methodAndTrim + ']';
  });
  return normalized.join('|');
}
function applyCalcMethod(scores, weight, method, trimH, trimL) {
  if (!scores.length) return { averageScore: 0, contributionScore: 0 };
  if (method === 'trim_extremes') {
    const totalTrim = (trimH || 0) + (trimL || 0);
    if (scores.length < totalTrim) return { averageScore: 0, contributionScore: 0 };
    const sorted = scores.slice().sort((a, b) => a - b);
    const trimmed = sorted.slice(trimL || 0, scores.length - (trimH || 0));
    if (!trimmed.length) return { averageScore: 0, contributionScore: 0 };
    const avg = trimmed.reduce((s, v) => s + v, 0) / trimmed.length;
    return { averageScore: roundScore(avg), contributionScore: roundScore(avg * weight) };
  }
  const avg = scores.reduce((s, v) => s + v, 0) / scores.length;
  return { averageScore: roundScore(avg), contributionScore: roundScore(avg * weight) };
}

